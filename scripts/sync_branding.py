#!/usr/bin/env python3
"""Apply the central display metadata and distribution identifiers."""
import argparse
import html
import json
from pathlib import Path
import re

parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
branding = json.loads((root / "config/branding.json").read_text())
name = branding["name"]
publisher = branding["publisher"]
identifier = branding["identifier"]
description = branding["description"]
if not re.fullmatch(r"[a-z][a-z0-9]*(?:\.[a-z][a-z0-9]*){2,}", identifier):
    parser.error("Use a reverse-DNS identifier with at least three lowercase components.")
changed = []


def update(relative, transform):
    path = root / relative
    original = path.read_text()
    result = transform(original)
    if result == original:
        return
    changed.append(relative)
    if not args.check:
        path.write_text(result)


def substitute(relative, pattern, replacement):
    update(relative, lambda contents: re.sub(pattern, lambda match: match[1] + replacement + match[2], contents))


def dart(value):
    return json.dumps(value).replace("$", r"\$")


update("lib/app/branding.dart", lambda _: (
    "// Generated by scripts/sync_branding.py.\n"
    "abstract final class Branding {\n"
    f"  static const name = {dart(name)};\n"
    f"  static const publisher = {dart(publisher)};\n"
    f"  static const identifier = {dart(identifier)};\n"
    "}\n"
))
substitute("android/app/src/main/AndroidManifest.xml", r'(android:label=")[^"]*(")', html.escape(name))
substitute("android/app/build.gradle.kts", r'(applicationId = ")[^"]*(")', identifier)
substitute("ios/Runner/Info.plist", r'(<key>CFBundleDisplayName</key>\s*<string>)[^<]*(</string>)', html.escape(name))
substitute("ios/Runner.xcodeproj/project.pbxproj", r'(PRODUCT_BUNDLE_IDENTIFIER = )[\w.]+?(\.RunnerTests;|;)', identifier)
substitute("macos/Runner/Configs/AppInfo.xcconfig", r'(PRODUCT_BUNDLE_IDENTIFIER = )[^\n]*()', identifier)
substitute("macos/Runner/Configs/AppInfo.xcconfig", r'(APP_DISPLAY_NAME = )[^\n]*()', name)
substitute("macos/Runner.xcodeproj/project.pbxproj", r'(PRODUCT_BUNDLE_IDENTIFIER = )[\w.]+?(\.RunnerTests;|;)', identifier)
substitute("windows/runner/main.cpp", r'(window.Create\(L")[^"]*(")', json.dumps(name)[1:-1])
substitute("windows/runner/Runner.rc", r'(VALUE "CompanyName", ")[^"]*(")', json.dumps(publisher)[1:-1])
substitute("windows/runner/Runner.rc", r'(VALUE "(?:FileDescription|ProductName)", ")[^"]*(")', json.dumps(name)[1:-1])
substitute("web/index.html", r'(<title>)[^<]*(</title>)', html.escape(name))
substitute("web/index.html", r'(name="apple-mobile-web-app-title" content=")[^"]*(")', html.escape(name))
substitute("web/index.html", r'(name="description" content=")[^"]*(")', html.escape(description))


def manifest(contents):
    fields = json.loads(contents)
    fields.pop("orientation", None)
    fields.update(name=name, short_name=name, description=description,
                  background_color=branding["webTheme"], theme_color=branding["webTheme"])
    return json.dumps(fields, indent=2) + "\n"


update("web/manifest.json", manifest)
if changed and args.check:
    parser.error("Run scripts/sync_branding.py to update " + ", ".join(changed))
